import unittest
from CINDES.evaluation import reader
path = '/u/jteuniss/CINDES/tests'

class Test_reader(unittest.TestCase):
    def setUp(self):
        import os
        pwd = os.getcwd()
        if debug: print("pwd:", pwd)
        self.zmatfile = path + '/testfiles/' + 'ZMAT'
        (zmat, fileid) = reader.zmatread(self.zmatfile)
        self.zmat      = zmat
        self.zdic      = reader.zmatvalues(fileid)

    def tearDown(self):
        pass

    # reads the initial zmatfile part
    def test_zmatread1(self):
        nlines = len(reader.zmatread(self.zmatfile)[0])
        if debug: print("nlines zmat:", nlines)
        self.assertTrue( nlines==21 )

    # reads the values concerned with the zmatfile
    def test_zmatvalues(self):
        nentries       = len(self.zdic)
        if debug: print("nentries", nentries)
        self.assertTrue( nentries == 54 )

    def test_zmatprinter(self):
        filled_zmat = reader.zmatprinter(self.zmat, self.zdic)
        self.assertEqual( filled_zmat, test_filz)

    def test_splitter(self):
        splitted   = reader.sitesplitter(test_filz, 4, (5, 12), 4 )
        self.assertEqual( test_splitted, splitted )

class Test_reader_geometry(unittest.TestCase):
    def setUp(self):
        self.zmatfile = path + '/testfiles/' + 'ZMAT'
        self.param = { 'ncore': 4, 'nch3':4, 'line1':(5,19) }

    def test_geometry(self):
        out = reader.geometry(zmatrixfile=self.zmatfile, **self.param)
        self.assertEqual( out, test_geom )


if __name__ == "__main__":
    unittest.main()


